// ============================================================================
//  T-16 PROGRAM ROM  ("the book of instructions")  —  V4.1
//  File    : rtl/t16_rom.v
//  256 words x 16 bits. Parameterizable depth for silicon optimization.
//
//  HOW THE PROGRAM GETS INTO THE ROM (V4.1 — two safe modes):
//
//    MODE A — SIMULATION (this is what run_sim.sh uses):
//      INIT_FILE is a real path like "sw/program_fib.hex", so the
//      $readmemh() call below loads it at time zero and OVERRIDES the
//      baked words. You can swap programs freely without touching RTL.
//
//    MODE B — SYNTHESIS / SILICON (OpenLane, TinyTapeout):
//      The silicon tops set INIT_FILE = "" (no file to find inside the
//      Docker container, where relative paths break). When INIT_FILE is
//      empty, $readmemh is never called and the BAKED WORDS below —
//      generated by tools/bake_rom.py from sw/program_fib.hex — are
//      what Yosys turns into real gates.
//
//      After changing your program for silicon, re-bake with:
//          python3 tools/bake_rom.py sw/your_program.hex
//
//    SAFETY: every word is pre-set to 0xF000 (HALT). If a readmemh file
//    is missing OR a baked word was never written, the CPU lands on HALT
//    and stops safely instead of executing garbage.
//
//  Project : TELUGU T-16 V4.1 | License : Apache-2.0
// ============================================================================

`timescale 1ns / 1ps

module t16_rom #(
    parameter ROM_DEPTH = 256,
    parameter INIT_FILE = ""
) (
    input  wire [15:0] addr,
    output wire [15:0] instr
);

    reg [15:0] mem [0:ROM_DEPTH-1];

    integer i;
    initial begin
        // 1) Safe default: the whole ROM is HALT padding.
        for (i = 0; i < ROM_DEPTH; i = i + 1)
            mem[i] = 16'hF000;

        // 2) Baked program words (generated — see tools/bake_rom.py).
        //    ---- T16_ROM_BAKE_BEGIN (do not edit by hand) ----
        mem[  0]  = 16'h6880;  // 000: LDI R4 0x80
        mem[  1]  = 16'h6000;  // 001: LDI R0 0
        mem[  2]  = 16'h6200;  // 002: LDI R1 0
        mem[  3]  = 16'h6401;  // 003: LDI R2 1
        mem[  4]  = 16'h660A;  // 004: LDI R3 10
        mem[  5]  = 16'h6C00;  // 005: LDI R6 0
        mem[  6]  = 16'h6E01;  // 006: LDI R7 1
        mem[  7]  = 16'h8500;  // 007: STM R2 R4 R0
        mem[  8]  = 16'h0A50;  // 008: ADD R5 R1 R2
        mem[  9]  = 16'h32B0;  // 009: OR R1 R2 R6
        mem[ 10]  = 16'h3570;  // 010: OR R2 R5 R6
        mem[ 11]  = 16'h16F8;  // 011: SUB R3 R3 R7
        mem[ 12]  = 16'hB7FA;  // 012: BNEZ R3 loop
        mem[ 13]  = 16'hF000;  // 013: HALT
        mem[ 14]  = 16'hF000;  // --- safety padding: the rest is HALT ---
        //    ---- T16_ROM_BAKE_END ----

        // 3) Simulation override: load the .hex file only when one is
        //    named. (File content wins over the baked words above.)
        if (INIT_FILE != "")
            $readmemh(INIT_FILE, mem);
    end

    assign instr = mem[addr[$clog2(ROM_DEPTH)-1:0]];

endmodule
